# Runs inside Blender's Python (bpy) - started by stage_run.py, never with uv.
"""Realistic actors: Rigify-rigged figures that play every call of the `Char` acting API (pose, hands, reach, look,
walk, hop, say, mood, nod, take ...), plus contact with the world after the animation is baked: feet stand on the
floor and make steps, arms do not reach through desks.

project.json `"figures": "rigify"` turns every figure `cast()` builds into an actor; `"actors": {"mo": "tim"}` says
which actor plays which part (default: the actor of the same name, else the project's own actors - or all - in
alphabetical order). One
figure only: `K.cast(S, {"tim": {"actor": "tim"}})` in any film.

How it works: the actor keeps the invisible joint skeleton of a `Char` (empties: hip, body, head, arm/fore/hand,
leg/shin/foot), laid out on the proportions of the Rigify rig. The rig bones copy the world rotation of helpers
hanging on these joints (arms and legs bound hanging straight down, as the toy limbs are), so all the acting code of
`Char` runs unchanged. Face: the sliders on the head bone (see FACE) take blinks, moods, brows and Rhubarb mouth
shapes. Legs are IK: their feet follow a target per foot that `contact()` writes after the bake.

The actor contract - a folder `<actors>/<name>/figur.blend` (the folders: `<project>/actors/`, then the machine
config key `actors3d`, env STAGE3D_ACTORS) with:
  - one armature generated by Rigify (human metarig): bones torso, chest, neck, head, upper_arm_fk/forearm_fk/hand_fk,
    thigh_fk/shin_fk, foot_ik, upper_arm_parent/thigh_parent (IK_FK) per side, ORG-* and DEF-* bones;
  - meshes and props parented to that armature (everything else in the file - cameras, lights, floors, the metarig -
    is left out);
  - optional face sliders as custom properties of the pose bone "head" (names in FACE; their values in the file are
    the rest face) and `<name>/mundformen.json` or `<actors>/mundformen.json` = Rhubarb shapes as slider mixes.
Figures of the 3D figure kit (experiments/20_3d_figur: bauen.py <name> --blend) fulfil it.
"""
