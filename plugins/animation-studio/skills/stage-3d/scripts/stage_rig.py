# ====================================================================== finding and loading actors
def actor_dirs():
    out = [_C.PROJECT / "actors"]
    for v in (os.environ.get("STAGE3D_ACTORS"), os.environ.get("ANIMATION_STUDIO_ACTORS3D")):
        if v:
            out += [Path(p) for p in v.split(os.pathsep) if p]
    return [d for d in out if d.is_dir()]


def available():
    """{actor name: figur.blend} of all actor folders (the project's own win)"""
    out = {}
    for d in reversed(actor_dirs()):
        for b in sorted(d.glob("*/figur.blend")):
            out[b.parent.name] = b
    return out


def actor_path(name):
    if str(name).endswith(".blend") and Path(name).exists():
        return Path(name)
    av = available()
    if name not in av:
        where = ", ".join(str(d) for d in actor_dirs()) or "none found"
        raise SystemExit(f'actor "{name}" not found (actor folders: {where}; actors: {", ".join(av) or "none"}) - put '
                         f"<name>/figur.blend into <project>/actors/ or set the machine config key actors3d")
    return av[name]


def pick(cast_name, i):
    """which actor plays a part: project.json "actors", else the actor of the same name, else the i-th actor"""
    if cast_name in ACTORS:
        return ACTORS[cast_name]
    av = available()
    if cast_name in av:
        return cast_name
    if not av:
        actor_path(cast_name)               # stops with the message where actors are looked for
    own = sorted(b.parent.name for b in (_C.PROJECT / "actors").glob("*/figur.blend"))
    names = own or sorted(av)               # the project's own actors first
    return names[i % len(names)]


def _load(path):
    """append the armature generated by Rigify and everything parented to it -> (rig, objects)"""
    with bpy.data.libraries.load(str(path), link=False) as (src, dst):
        dst.objects = [n for n in src.objects if not n.startswith("WGT-")]
    obs = [o for o in dst.objects if o is not None]
    rigs = [o for o in obs if o.type == "ARMATURE" and "upper_arm_fk.L" in o.data.bones and "torso" in o.data.bones]
    if not rigs:
        raise SystemExit(f"{path}: no armature generated by Rigify (bones torso, upper_arm_fk.L ...) in it")
    rig = rigs[0]

    def under(o):
        while o is not None:
            if o == rig:
                return True
            o = o.parent
        return False

    keep = [o for o in obs if under(o) and o.type not in ("CAMERA", "LIGHT") and o.name.split(".")[0] not in DROP]
    for o in obs:
        if o not in keep:
            bpy.data.objects.remove(o, do_unlink=True)
    for o in keep:                    # old animations go, drivers stay (face sliders -> shape keys, Rigify switches)
        for idb in (o, o.data, getattr(o.data, "shape_keys", None)):
            ad = getattr(idb, "animation_data", None) if idb is not None else None
            if ad is not None and ad.action is not None:
                ad.action = None
        if o.type == "MESH" and o.data.shape_keys:
            for kb in o.data.shape_keys.key_blocks[1:]:
                kb.slider_max = max(kb.slider_max, 2.0)      # rest face = expression keys at 1, moods go up to 2
    return rig, keep


# ====================================================================== the actor
class RigActor(Char):
    """a Rigify figure as a Char: same acting API, own proportions (taken from the rig)"""
    mouth_rest = 0.0
    mouth_closed = 0.0
    mouth_gain = 1.0
    speech_gain = 1.0
    step_len = 8
    rest_over = {}
    step = dict(dist=0.035, angle=14.0, frames=6, lift=0.045, jump=0.25, up=0.035)   # feet (x size): see contact()

    def __init__(self, S, name, actor, size=1.0, height=None):
        self.actor = actor
        self.blend = actor_path(actor)
        self.rig, self.obs = _load(self.blend)
        self.coll = bpy.data.collections.new(f"{name}_actor")
        bpy.context.scene.collection.children.link(self.coll)
        for o in self.obs:
            for c in list(o.users_collection):
                c.objects.unlink(o)
            self.coll.objects.link(o)
        self.rig.matrix_world = Matrix.Identity(4)
        pb = self.rig.pose.bones
        for b in pb:
            b.location, b.scale = (0, 0, 0), (1, 1, 1)
            b.rotation_mode = "QUATERNION"
            b.rotation_quaternion = (1, 0, 0, 0)
        bpy.context.view_layer.update()
        top = max((o.matrix_world @ V(bb)).z for o in self.obs if o.type == "MESH" for bb in o.bound_box)
        self.native_h = top
        if height:
            size = height / top
        self._spoken = []
        super().__init__(S, name, size)
        print(f"ACTOR {name}: {self.actor} ({self.blend}), {top * self.size:.2f} m", flush=True)
        _register(S, self)

    # ---- the skeleton of the Char on the proportions of the rig
    def build(self):
        rig, pb, B = self.rig, self.rig.pose.bones, self.rig.data.bones
        P = lambda b: B[b].head_local.copy()                                         # noqa: E731
        L = lambda b: (B[b].tail_local - B[b].head_local).length                     # noqa: E731
        chest, neck = P("chest"), P("neck")
        self.body_z0 = chest.z
        self.drop_len = (P("thigh_fk.L").z - P("shin_fk.L").z) / 0.8      # "sit": thighs level, feet on the floor
        body = self.j("body", (0, 0, chest.z), self.hip)
        self.j("head", tuple(neck - chest), body)
        hb = B["head"]
        self.head_z = hb.head_local.z + 0.5 * (hb.tail_local.z - hb.head_local.z)
        eyes = [o for o in self.obs if o.type == "MESH" and o.name.lower().startswith(("augapfel", "eye", "auge"))]
        self.eye_z = (sum(o.matrix_world.translation.z for o in eyes) / len(eyes) if eyes
                      else hb.head_local.z + 0.42 * (hb.tail_local.z - hb.head_local.z))
        self.torso_front = self._front(chest.z + 0.03) or 0.1
        for s in "LR":
            sh = P(f"upper_arm_fk.{s}")
            l1, l2 = L(f"upper_arm_fk.{s}"), L(f"forearm_fk.{s}")
            up = self.j("arm" + s, tuple(sh - chest), body)
            fo = self.j("fore" + s, (0, 0, -l1), up)
            self.j("hand" + s, (0, 0, -l2), fo)
            self.arm_geo[s] = (V(sh - chest), l1, l2)
        for s in "LR":
            th = P(f"thigh_fk.{s}")
            up = self.j("leg" + s, tuple(th), self.hip)
            sn = self.j("shin" + s, (0, 0, -L(f"thigh_fk.{s}")), up)
            self.j("foot" + s, (0, 0, -L(f"shin_fk.{s}")), sn)
        self.leg_len = L("thigh_fk.L") + L("shin_fk.L")
        # the rig hangs on the squash node (hops, squash and stretch); bones follow helpers on the joints
        rig.parent = self.sq.obj
        rig.matrix_parent_inverse = Matrix.Identity(4)
        bpy.context.view_layer.update()
        for s in "LR":
            pb[f"upper_arm_parent.{s}"]["IK_FK"] = 1.0                       # arms FK (the Char solves its own IK)
            pb[f"thigh_parent.{s}"]["IK_FK"] = 0.0                           # legs IK on the foot targets
            pb[f"thigh_parent.{s}"]["IK_Stretch"] = 0.0                      # a foot out of reach: no rubber leg
        down = V((0, 0, -1))
        bind = [("hip", "torso", True, None, 1.0), ("body", "chest", False, None, 1.0),
                ("head", "neck", False, None, 0.5), ("head", "head", False, None, 1.0)]
        for s in "LR":
            bind += [("arm" + s, f"upper_arm_fk.{s}", False, down, 1.0),
                     ("fore" + s, f"forearm_fk.{s}", False, down, 1.0),
                     ("hand" + s, f"hand_fk.{s}", False, down, 1.0),
                     ("leg" + s, f"thigh_fk.{s}", False, down, 1.0),
                     ("shin" + s, f"shin_fk.{s}", False, down, 1.0)]
        for jn, bone, loc, align, infl in bind:
            h = self._helper(jn, bone, align)
            self._follow(pb[bone], h, loc, infl)
        # feet: a free helper on the Char foot (where the leg puts the foot) and the target the IK foot follows
        self.free, self.target = {}, {}
        for s in "LR":
            self.free[s] = self._helper("foot" + s, f"foot_ik.{s}", None)
            t = empty(f"{self.name}_feet{s}")
            t.rotation_mode = "QUATERNION"
            t.matrix_world = self.free[s].matrix_world.copy()
            self.target[s] = t
            self._follow(pb[f"foot_ik.{s}"], t, True, 1.0)
        bpy.context.view_layer.update()
        root = self.root.obj.matrix_world.translation
        self.ankle = {s: self.free[s].matrix_world.translation.z - root.z for s in "LR"}
        self.own = {o.name for o in self.obs}
        self.foot_rest = {s: self.free[s].matrix_world.to_quaternion() for s in "LR"}
        # face sliders present in this figure, with their rest values
        hp = pb["head"]
        self.face = {k: (n, float(hp[n])) for k, n in FACE.items() if n in hp}
        sh = self.blend.parent / "mundformen.json"
        sh = sh if sh.exists() else self.blend.parent.parent / "mundformen.json"
        self.shapes = dict(SHAPES)
        if sh.exists():
            self.shapes.update({k: v for k, v in json.loads(sh.read_text(encoding="utf-8")).items()
                                if not k.startswith("_")})

    def _front(self, z):
        """distance of the chest surface in front of the body axis at height z (rest pose)"""
        best = 0.0
        for o in self.obs:
            if o.type != "MESH" or not any(m.type == "ARMATURE" for m in o.modifiers):
                continue
            mw = o.matrix_world
            for v in o.data.vertices:
                p = mw @ v.co
                if abs(p.z - z) < 0.03 and abs(p.x) < 0.04:
                    best = max(best, -p.y)
        return best

    def _helper(self, joint, bone, align):
        """an empty on Char joint `joint` with the rest orientation of `bone` (turned so that the bone points along
        `align` when the joint is at rest)"""
        j = self.J[joint].obj
        h = empty(f"{self.name}_{joint}_{bone}", parent=j)
        h.empty_display_size = 0.02
        mb = self.rig.matrix_world @ self.rig.data.bones[bone].matrix_local
        if align is not None:
            d = (mb.to_3x3() @ V((0, 1, 0))).normalized()
            R = d.rotation_difference(align).to_matrix().to_4x4()
            mb = Matrix.Translation(mb.translation) @ R @ Matrix.Translation(-mb.translation) @ mb
        h.matrix_world = mb
        return h

    @staticmethod
    def _follow(pbone, target, loc, infl):
        c = pbone.constraints.new("COPY_ROTATION")
        c.name = "stage_rot"
        c.target, c.owner_space, c.target_space, c.influence = target, "WORLD", "WORLD", infl
        if loc:
            c = pbone.constraints.new("COPY_LOCATION")
            c.name = "stage_loc"
            c.target, c.owner_space, c.target_space = target, "WORLD", "WORLD"

    # ---- face
    def _face(self, key):
        """the stage channel of a face slider (None if the figure has no such slider)"""
        if key not in self.face:
            return None
        n, rest = self.face[key]
        return self.S.ch(self.rig, f'pose.bones["head"]["{n}"]', 0, default=rest)

    def _face_key(self, f, key, delta, ease="io"):
        c = self._face(key)
        if c is not None:
            c.key(f, clamp(self.face[key][1] + delta, 0.0, 2.0), ease)

    def alive(self):
        super().alive()                                  # breathing, sway, head drift, blink times
        lid = self._face("lids")
        if lid is not None:
            rest = self.face["lids"][1]
            lid.add(lambda f: max(0.0, (1.0 - self._blink_fn(f)) / 0.92 - rest))
        for k in MOUTH:
            c = self._face(k)
            if c is not None:
                c.add(lambda f, k=k: self._mouth(f, k))

    def _mouth(self, f, k):
        """mouth slider k at frame f: Rhubarb shapes while a line is spoken, else the mouth channel opens the mouth"""
        n, rest = self.face[k]
        for f0, f1, cs in self._spoken:
            if f0 - 2 <= f <= f1 + 2:
                v = 0.0
                for d, w in ((-1, 0.25), (0, 0.5), (1, 0.25)):
                    shape = self._shape_at(cs, f0, f + d)
                    v += w * (rest if shape == "X" else self.shapes.get(shape, {}).get(n, 0.0))
                return v - rest
        if k == "open":
            return 0.8 * clamp(self.mouth_ch.eval(f), 0.0, 1.3)
        return 0.0

    @staticmethod
    def _shape_at(cs, f0, f):
        t = (f - f0 + 1) / FPS
        out = "X"
        for c in cs:
            if c["start"] <= t + 1e-6:
                out = c["value"]
            else:
                break
        return out

    def say(self, zid, f0, gesture=1.0, nod=1.0):
        last = super().say(zid, f0, gesture, nod)
        self._spoken.append((int(f0), int(last), cues(zid)))
        return last

    def mood(self, f, name, ease="io"):
        from stage_actor import MOODS
        super().mood(f, name, ease)
        m = MOODS[name]                                 # (super().mood already set the brows through brows_set)
        e = m.get("eyes", 1.0)
        self._face_key(f, "eyes_wide", max(0.0, e - 1.0) * 3.0, ease)
        self._face_key(f, "eyes_narrow", max(0.0, 1.0 - e) * 0.7, ease)
        if "lids" in self.face:                         # sleepy: heavy lids, never shut
            self._face_key(f, "lids", min(0.45, max(0.0, 0.75 - e) * 1.2), ease)
        sm, dn = MOOD_FACE.get(name, (0.0, 0.0))
        self._face_key(f, "smile", sm, ease)
        self._face_key(f, "down", dn, ease)
        return self

    def brows_set(self, f, up=0, tilt=0, ease="io"):
        for s in "LR":
            u = up[0 if s == "L" else 1] if isinstance(up, (tuple, list)) else up
            t = tilt[0 if s == "L" else 1] if isinstance(tilt, (tuple, list)) else tilt
            self._face_key(f, "brow" + s, 0.35 * u, ease)
            self._face_key(f, f"inner{s}_up", max(0.0, t) / 20.0, ease)
            self._face_key(f, f"inner{s}_down", max(0.0, -t) / 14.0, ease)
        return self

    def take(self, f, amp=1.0):
        super().take(f, amp)
        c = self._face("eyes_wide")
        if c is not None:
            v = c.last(f)
            c.key(f + 4, v)
            c.key(f + 7, clamp(v + 0.9 * amp, 0, 2), "out")
            c.key(f + 20, clamp(v + 0.9 * amp, 0, 2), "hold")
            c.key(f + 28, v)
        return self

    # ---- staging
    def walk(self, f0, f1, x, y, face=True, bob=0.03, swing=28, arms=True, turn=6):
        """walk to (x, y): the feet make their steps by themselves (contact), so only body bob, sway and arm swing
        are added here"""
        p = self.pos(f0)
        if face and (abs(x - p.x) + abs(y - p.y)) > 1e-4:
            self.face_to(max(1, f0 - turn), (x, y, 0), turn)
        self.root.loc(f0, p.x, p.y)
        self.root.loc(f1, x, y, ease="io")
        w = lambda f: smooth((f - f0) / 4) * smooth((f1 - f) / 4)     # noqa: E731
        sl = self.step_len
        ph = lambda f: (f - f0) / sl * math.pi                        # noqa: E731
        self.sq.lch(2).add(lambda f: w(f) * bob * 0.5 / self.size * abs(math.sin(ph(f))) if f0 <= f <= f1 else 0.0)
        self.body.rch(1).add(lambda f: w(f) * 3 * math.sin(ph(f)) if f0 <= f <= f1 else 0.0)
        self.body.rch(2).add(lambda f: w(f) * 5 * math.sin(ph(f)) if f0 <= f <= f1 else 0.0)
        if arms:
            for s, sg in (("L", 1), ("R", -1)):
                self.J["arm" + s].rch(0).add(
                    lambda f, sg=sg: -w(f) * swing * 0.6 * sg * math.sin(ph(f)) if f0 <= f <= f1 else 0.0)
        return [f0 + int(i * sl) for i in range(1, int((f1 - f0) / sl) + 1)]

    def hold_prop(self, obj, side="R", loc=(0, 0, 0), rot=(0, 0, 0)):
        """a prop in the hand, on the rig's hand bone (loc/rot relative to the finger end of the hand, m / degrees)"""
        obj.parent = self.rig
        obj.parent_type = "BONE"
        obj.parent_bone = f"ORG-hand.{side}"
        obj.location = loc
        obj.rotation_euler = [math.radians(a) for a in rot]
        return obj


def actor(S, cast_name, spec, i=0):
    """build an actor from a cast() spec: "tim" / {"actor": "tim", "size": 1.1, "height": 1.0} / a toy spec (its
    look is ignored; the actor comes from project.json "actors" or pick())"""
    d = {} if isinstance(spec, str) else dict(spec)
    name = d.get("actor") or (spec if isinstance(spec, str) and spec in available() else pick(cast_name, i))
    return RigActor(S, cast_name, name, size=d.get("size", 1.0), height=d.get("height"))


# ====================================================================== contact (after the bake)
OBSTACLE = ("desk", "table", "keyboard", "monitor", "screen", "piano", "counter", "shelf", "cabinet", "laptop",
            "tisch", "pult", "tastatur", "klavier", "kasse", "server", "schirm", "korpus", "sockel", "fensterbank")
REACH = dict(margin=0.008, max=75.0, near=0.35)        # m from the surface, degrees at most, m around the wrist
_ACTORS = {}


def _register(S, a):
    if S not in _ACTORS:
        _ACTORS[S] = []
        orig = S.bake

        def bake():
            orig()
            contact(S, os.environ.get("STAGE3D_CONTACT", "1") != "0")
        S.bake = bake
    _ACTORS[S].append(a)


def obstacle(*objs, on=True):
    """mark objects (and their children) as furniture the arms must not reach through (on=False: never)"""
    for o in objs:
        o = o.obj if isinstance(o, Node) else o
        for x in [o] + list(o.children_recursive):
            x["obstacle"] = 1 if on else 0
    return objs


def contact(S, on=True):
    """after the bake: feet (planted steps; on=False: they only follow the legs) and arms off the furniture"""
    import time
    t0 = time.time()
    acts = _ACTORS.get(S, [])
    if not acts:
        return
    n_feet = _feet(S, acts, plant=on)
    n_arms = _arms(S, acts) if on else 0
    print(f"CONTACT {len(acts)} actors: {n_feet} foot steps, {n_arms} arm frames moved off furniture, "
          f"{time.time() - t0:.1f}s", flush=True)


def _write(obj, path, idx, vals):
    """one linear key per frame on an object's own action (stage_core.Stage.bake layout)"""
    ad = obj.animation_data or obj.animation_data_create()
    if ad.action is None:
        act = bpy.data.actions.new("a_" + obj.name)
        slot = act.slots.new(id_type=obj.id_type, name=obj.name)
        act.layers.new("L").strips.new(type="KEYFRAME")
        ad.action, ad.action_slot = act, slot
    cb = ad.action.layers[0].strips[0].channelbag(ad.action_slot, ensure=True)
    fc = cb.fcurves.find(path, index=idx)
    if fc is not None:
        cb.fcurves.remove(fc)
    fc = cb.fcurves.new(path, index=idx)
    fc.keyframe_points.add(len(vals))
    fc.keyframe_points.foreach_set("co", [x for i, v in enumerate(vals) for x in (i + 1, v)])
    fc.keyframe_points.foreach_set("interpolation", [1] * len(vals))
    fc.update()


def _wrap(a):
    return (a + math.pi) % math.tau - math.pi


def _yaw(q, rest):
    x = (q @ rest.inverted()) @ V((1, 0, 0))
    return math.atan2(x.y, x.x)


def _ground(sc, dg, p, z0, a):
    """height of the floor under a foot: the first surface below the ankle (rug, step, stage) - not deeper than
    10 cm below / higher than 15 cm above the figure's own ground (the root); else the root height"""
    k = a.size
    start = V((p.x, p.y, max(p.z, z0 + a.ankle["L"]) + 0.05 * k))
    for _ in range(6):
        hit, loc, _n, _i, ob, _m = sc.ray_cast(dg, start, V((0, 0, -1)), distance=0.4 * k)
        if not hit:
            break
        if ob.name in a.own or ob.hide_render:
            start = loc + V((0, 0, -1e-4))
            continue
        if z0 - 0.10 * k <= loc.z <= z0 + 0.15 * k:
            return loc.z
        break
    return z0


def _feet(S, acts, plant=True):
    """IK foot targets: a foot near the floor stands still until the body has moved away from it, then makes a
    step (one foot at a time); lifted feet (hops, sitting, kicks) follow the leg; soles stay flat on the floor"""
    sc, n = S.scene, S.frames
    own = set()
    for a in acts:
        own.update(o.name for o in a.obs)
    hide = [o for o in sc.objects if o.type == "MESH" and not o.hide_viewport and o.name in own]
    for o in hide:
        o.hide_viewport = True                  # the actors' own meshes are not needed (and are the slow part)
    rows = {a: [] for a in acts}
    try:
        for f in range(1, n + 1):
            sc.frame_set(f)
            dg = bpy.context.evaluated_depsgraph_get()
            for a in acts:
                z0 = a.root.obj.matrix_world.translation.z
                row = {}
                for s in "LR":
                    m = a.free[s].matrix_world
                    row[s] = (m.translation.copy(), m.to_quaternion(), _ground(sc, dg, m.translation, z0, a))
                rows[a].append(row)
    finally:
        for o in hide:
            o.hide_viewport = False
    steps = 0
    for a in acts:
        k = a.size
        st = a.step
        dur = st["frames"]
        home = [{s: V((r[s][0].x, r[s][0].y, r[s][2] + a.ankle[s])) for s in "LR"} for r in rows[a]]
        free = [{s: not plant or r[s][0].z - (r[s][2] + a.ankle[s]) > st["up"] * k for s in "LR"} for r in rows[a]]
        yaws = [{s: _yaw(r[s][1], a.foot_rest[s]) for s in "LR"} for r in rows[a]]
        F = {s: dict(at=None, yaw=0.0, step=None, blend=0) for s in "LR"}
        mid = [(h["L"] + h["R"]) * 0.5 for h in home]
        stride = 1.5 * a.leg_len * k                     # preferred stride of one foot while walking
        out = {s: [] for s in "LR"}
        for i in range(n):
            moving = [s for s in "LR" if F[s]["step"] is not None]
            if not moving:
                err = {s: ((home[i][s] - F[s]["at"]).length
                           + 0.0025 * abs(math.degrees(_wrap(yaws[i][s] - F[s]["yaw"]))))
                       if F[s]["at"] is not None and not free[i][s] else 0.0 for s in "LR"}
                s = max(err, key=err.get)
                if F[s]["at"] is not None and not free[i][s]:
                    far = (home[i][s] - F[s]["at"]).length
                    if i and (mid[i] - mid[i - 1]).length > st["jump"] * k:   # the body jumped in one frame
                        for x in "LR":                           # a cut / teleport: both feet go along at once
                            if F[x]["at"] is not None:
                                F[x].update(at=home[i][x].copy(), yaw=yaws[i][x])
                    else:
                        turn = abs(math.degrees(_wrap(yaws[i][s] - F[s]["yaw"]))) > st["angle"]
                        v = (mid[min(n - 1, i + 2)] - mid[max(0, i - 2)]) / 4.0          # body speed (m / frame)
                        sp = v.xy.length
                        go, d, lead = False, dur, V()
                        if sp > 0.008 * k:                       # walking: a gait cycle that fits the speed
                            T = min(max(stride / sp, 6.0), 2.0 * a.step_len)
                            L = sp * T
                            dv = v.normalized()
                            d = max(4, round(0.42 * T))
                            behind = -(F[s]["at"] - home[i][s]).dot(dv)
                            go = behind > 0.3 * L or turn or far > 0.6 * L
                            lead = dv * (0.3 * L)
                        else:                                    # standing, dancing, shifting: small steps
                            go = far > st["dist"] * k or turn
                        if go:
                            e = min(n - 1, i + d)
                            F[s]["step"] = (i, F[s]["at"].copy(), F[s]["yaw"], home[e][s] + lead,
                                          F[s]["yaw"] + _wrap(yaws[e][s] - F[s]["yaw"]), d)
                            steps += 1
            for s in "LR":
                z = F[s]
                fm, fq = rows[a][i][s][0], rows[a][i][s][1]
                if free[i][s]:                                   # lifted: the foot goes with the leg
                    if z["at"] is not None:
                        z.update(blend=4, last=(z["at"].copy(), z["yaw"]))
                    z.update(at=None, step=None)
                    p, q = fm, fq
                    if z["blend"]:
                        b = 1 - z["blend"] / 5
                        lp, ly = z["last"]
                        flat = Quaternion((0, 0, 1), ly) @ a.foot_rest[s]
                        p, q = lp.lerp(fm, b), flat.slerp(fq, b)
                        z["blend"] -= 1
                    out[s].append((p, q))
                    continue
                if z["at"] is None:                              # lands / first frame: stands where the leg put it
                    z.update(at=home[i][s].copy(), yaw=yaws[i][s])
                if z["step"] is not None:
                    i0, frm, y0, to, y1, d = z["step"]
                    u = (i - i0) / d
                    if u >= 1.0:
                        z.update(at=to.copy(), yaw=y1, step=None)
                        p, yw = z["at"], y1
                    else:
                        e = u * u * (3 - 2 * u)
                        p = frm.lerp(to, e) + V((0, 0, st["lift"] * k * math.sin(math.pi * u)))
                        yw = y0 + (y1 - y0) * e
                else:
                    p, yw = z["at"], z["yaw"]
                out[s].append((p.copy(), Quaternion((0, 0, 1), yw) @ a.foot_rest[s]))
        for s in "LR":
            t = a.target[s]
            prev = None
            qs = []
            for _p, q in out[s]:
                if prev is not None and prev.dot(q) < 0:
                    q = -q
                qs.append(q)
                prev = q
            for c in range(3):
                _write(t, "location", c, [p[c] for p, _ in out[s]])
            for c in range(4):
                _write(t, "rotation_quaternion", c, [q[c] for q in qs])
    return steps


def _obstacles(acts):
    own = set()
    for a in acts:
        own.update(o.name for o in a.obs)
        own.update(o.name for o in a.root.obj.children_recursive)
    out = []
    for o in bpy.context.scene.objects:
        if o.type != "MESH" or o.name in own:
            continue
        flag, chain, p = o.get("obstacle"), [o.name.lower()], o.parent
        while p is not None:
            chain.append(p.name.lower())
            if flag is None:
                flag = p.get("obstacle")
            p = p.parent
        if flag is not None:
            if flag:
                out.append(o)
            continue
        if any(k in n for n in chain for k in OBSTACLE) and max(o.dimensions) >= 0.12:
            out.append(o)
    return out


def _chain(a, side):
    """world points shoulder, wrist + samples along arm and hand (ORG bones of the rig)"""
    mw, pb = a.rig.matrix_world, a.rig.pose.bones
    s = mw @ pb[f"ORG-upper_arm.{side}"].head
    e = mw @ pb[f"ORG-forearm.{side}"].head
    w = mw @ pb[f"ORG-hand.{side}"].head
    t = mw @ pb[f"ORG-hand.{side}"].tail
    t = t + (t - w).normalized() * 0.05 * a.size
    pts = [s.lerp(e, u) for u in (0.5, 0.75, 1.0)] + [e.lerp(w, u) for u in (0.25, 0.5, 0.75, 1.0)] + \
          [w.lerp(t, u) for u in (0.33, 0.66, 1.0)]
    return s, w, pts


def _hand_samples(a, dg):
    """{side: [(obj, [vertex index])]}: hand, fingers and forearm sleeve on the evaluated meshes (<= ~150 per side)"""
    gr = ("DEF-hand", "DEF-f_", "DEF-thumb", "DEF-palm", "DEF-forearm")
    out = {"L": [], "R": []}
    for o in a.obs:
        if o.type != "MESH" or not any(g.name.startswith(gr) for g in o.vertex_groups):
            continue
        idx = {g.index: g.name for g in o.vertex_groups if g.name.startswith(gr)}
        oe = o.evaluated_get(dg)
        m = oe.to_mesh()
        for sd in "LR":
            vs = [v.index for v in m.vertices
                  if any(g.group in idx and g.weight > 0.5 and idx[g.group].endswith("." + sd) for g in v.groups)]
            if vs:
                out[sd].append((o, vs[::max(1, len(vs) // 120)]))
        oe.to_mesh_clear()
    return out


def _mesh_points(samples, dg):
    pts = []
    for o, vs in samples:
        if o.hide_render:
            continue
        oe = o.evaluated_get(dg)
        m = oe.to_mesh()
        mw = oe.matrix_world
        n = len(m.vertices)
        pts += [mw @ m.vertices[i].co for i in vs if i < n]
        oe.to_mesh_clear()
    return pts


def _tree(o, dg, cache):
    from mathutils.bvhtree import BVHTree
    mw = o.matrix_world
    key = tuple(round(x, 5) for r in mw for x in r)
    c = cache.get(o.name)
    if c is None or c[0] != key:
        oe = o.evaluated_get(dg)
        me = oe.to_mesh()
        vs = [mw @ v.co for v in me.vertices]
        t = BVHTree.FromPolygons(vs, [tuple(p.vertices) for p in me.polygons]) if len(me.polygons) else None
        oe.to_mesh_clear()
        lo = V([min(v[i] for v in vs) for i in range(3)]) if vs else V()
        hi = V([max(v[i] for v in vs) for i in range(3)]) if vs else V()
        c = cache[o.name] = (key, t, lo, hi)
    return c[1], c[2], c[3]


def _inside(trees, pts):
    """how many points are in (or closer than the margin to) an obstacle"""
    n, m = 0, REACH["margin"]
    r = m + 0.002
    for t, lo, hi in trees:
        for p in pts:
            if not (lo.x - r < p.x < hi.x + r and lo.y - r < p.y < hi.y + r and lo.z - r < p.z < hi.z + r):
                continue
            loc, nor, _, d = t.find_nearest(p, 0.25)
            if loc is not None and (p - loc).dot(nor) < m:
                n += 1
    return n


def _arms(S, acts):
    """an arm whose hand or sleeve is in a desk is turned about the shoulder - up or down, whichever frees it with
    the smaller angle - with a soft fade in and out; the turn goes onto the Char arm joint (the rig follows)"""
    sc, n = S.scene, S.frames
    obst = _obstacles(acts)
    if not obst:
        return 0
    sc.frame_set(1)
    samples = [_hand_samples(a, bpy.context.evaluated_depsgraph_get()) for a in acts]
    ang = {(i, s): [0.0] * (n + 1) for i in range(len(acts)) for s in "LR"}
    axis = {(i, s): [None] * (n + 1) for i in range(len(acts)) for s in "LR"}
    cache = {}
    near = REACH["near"]
    for f in range(1, n + 1):
        sc.frame_set(f)
        dg = bpy.context.evaluated_depsgraph_get()
        seen = [o for o in obst if not o.hide_render and min(abs(v) for v in o.matrix_world.to_scale()) > 1e-3]
        if not seen:
            continue
        for i, a in enumerate(acts):
            if min(a.root.obj.matrix_world.to_scale()) < 0.2 * a.size:
                continue
            for s in "LR":
                sh, w, kp = _chain(a, s)
                ax = (kp[-1] - sh).cross(V((0, 0, 1)))
                if ax.length < 1e-4:
                    continue
                ax.normalize()
                axis[i, s][f] = ax
                trees = []
                for o in seen:
                    t, lo, hi = _tree(o, dg, cache)
                    if t is not None and all(lo[c] - near < w[c] < hi[c] + near for c in range(3)):
                        trees.append((t, lo, hi))
                if not trees:
                    continue
                pts = kp + _mesh_points(samples[i][s], dg)
                n0 = _inside(trees, pts)
                if n0 == 0:
                    continue
                best, th = (n0, 0.0), None
                for k in range(1, int(REACH["max"] / 2) + 1):
                    for sg in (1, -1):                         # same angle: rather lift
                        R = Matrix.Rotation(math.radians(sg * 2.0 * k), 3, ax)
                        c = _inside(trees, [sh + R @ (p - sh) for p in pts])
                        if c == 0:
                            th = sg * 2.0 * k
                            break
                        if c < best[0]:
                            best = (c, sg * 2.0 * k)
                    if th is not None:
                        break
                ang[i, s][f] = th if th is not None else best[1]
    moved = 0
    for (i, s), w in ang.items():
        if max(abs(x) for x in w) <= 0:
            continue
        d = [max(w[max(1, f - 3):min(n, f + 3) + 1], key=abs) for f in range(n + 1)]
        g = [0.0] * (n + 1)
        for f in range(1, n + 1):
            ks = [(k, 5 - abs(k)) for k in range(-4, 5) if 1 <= f + k <= n]
            g[f] = sum(d[f + k] * gw for k, gw in ks) / sum(gw for _, gw in ks)
            if w[f] and (abs(g[f]) < abs(w[f]) or g[f] * w[f] < 0):
                g[f] = w[f]
        a = acts[i]
        J = a.J["arm" + s].obj
        ad = J.animation_data
        if ad is None or ad.action is None:
            continue
        cb = ad.action.layers[0].strips[0].channelbag(ad.action_slot)
        fcs = [cb.fcurves.find("rotation_euler", index=c) for c in range(3)]
        if any(c is None for c in fcs):
            continue
        last = None
        new = {}
        for f in range(1, n + 1):
            ax = axis[i, s][f] or last
            last = ax
            if abs(g[f]) < 0.3 or ax is None:
                continue
            sc.frame_set(f)
            Jw = J.matrix_world.copy()
            piv = Jw.translation
            R = Matrix.Translation(piv) @ Matrix.Rotation(math.radians(g[f]), 4, ax) @ Matrix.Translation(-piv)
            loc = J.parent.matrix_world.inverted() @ (R @ Jw) if J.parent else R @ Jw
            new[f] = loc.to_euler("XYZ", J.matrix_basis.to_euler("XYZ"))
            moved += 1
        for f, e in new.items():
            for c, fc in enumerate(fcs):
                for kp in fc.keyframe_points:
                    if abs(kp.co.x - f) < 1e-3:
                        kp.co.y = e[c]
                        kp.handle_left.y = kp.handle_right.y = e[c]
        for fc in fcs:
            fc.update()
    return moved


