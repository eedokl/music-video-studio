def report(S, path=None):
    """per frame: how deep shoes are in the floor under them and how many hand points are in furniture
    -> {"feet": [{f, actor, side, cm}], "hands": [{f, actor, side, points}]} (also written to path)"""
    acts = _ACTORS.get(S, [])
    sc = S.scene
    obst = _obstacles(acts)
    own = set()
    for a in acts:
        own.update(o.name for o in a.obs)
    feet_g = ("DEF-foot", "DEF-toe")
    sc.frame_set(1)
    dg = bpy.context.evaluated_depsgraph_get()
    soles = []
    for a in acts:
        for o in a.obs:
            if o.type != "MESH":
                continue
            idx = {g.index: g.name for g in o.vertex_groups if g.name.startswith(feet_g)}
            if not idx:
                continue
            oe = o.evaluated_get(dg)
            m = oe.to_mesh()
            for sd in "LR":
                vs = [v.index for v in m.vertices
                      if any(g.group in idx and g.weight > 0.5 and idx[g.group].endswith("." + sd) for g in v.groups)]
                if vs:
                    soles.append((a, sd, o, vs[::max(1, len(vs) // 200)]))
            oe.to_mesh_clear()
    samples = [_hand_samples(a, dg) for a in acts]
    out = {"feet": [], "hands": []}
    cache = {}
    for f in range(1, S.frames + 1):
        sc.frame_set(f)
        dg = bpy.context.evaluated_depsgraph_get()
        for a, sd, o, vs in soles:
            pts = _mesh_points([(o, vs)], dg)
            if not pts:
                continue
            low = min(pts, key=lambda p: p.z)
            start, floor = low + V((0, 0, 0.15)), None
            for _ in range(12):
                hit, loc, nor, _i, ob, _m = sc.ray_cast(dg, start, V((0, 0, -1)), distance=2.0)
                if not hit:
                    break
                if ob.name in own:
                    start = loc + V((0, 0, -1e-4))
                    continue
                floor = loc.z
                break
            if floor is not None and floor - low.z > 0.004:
                out["feet"].append(dict(f=f, actor=a.name, side=sd, cm=round((floor - low.z) * 100, 1)))
        for i, a in enumerate(acts):
            for sd in "LR":
                _sh, w, kp = _chain(a, sd)
                trees = []
                for ob in obst:
                    if ob.hide_render:
                        continue
                    t, lo, hi = _tree(ob, dg, cache)
                    if t is not None and all(lo[c] - 0.35 < w[c] < hi[c] + 0.35 for c in range(3)):
                        trees.append((t, lo, hi))
                if trees:
                    k = _inside(trees, kp + _mesh_points(samples[i][sd], dg))
                    if k:
                        out["hands"].append(dict(f=f, actor=a.name, side=sd, points=k))
    if path:
        Path(path).write_text(json.dumps(out), encoding="utf-8")
    deep = max([x["cm"] for x in out["feet"]], default=0.0)
    print(f"CONTACT REPORT feet below the floor in {len({x['f'] for x in out['feet']})} frames (deepest {deep} cm), "
          f"hands in furniture in {len({x['f'] for x in out['hands']})} frames", flush=True)
    return out
