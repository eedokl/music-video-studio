"""Create a scene folder for a Synfig scene written in Python.

Usage: python new_scene.py <folder> [--from example|figure|blank|none] [--force]

Writes into <folder>:
  _toon.py       tiny path shim: `import _toon` in make_scene.py puts the toon-2d scripts (sif, motion, svg2sif,
                 lipsync, render ...) and the characters scripts (pip_figure, figures) on sys.path. It holds NO path:
                 it finds the plugin at run time, so scene folders keep working after a plugin update or move.
                 Lookup: env CLAUDE_PLUGIN_ROOT, then the machine config entry `animation_studio_root`
                 (env ANIMATION_STUDIO_ROOT or ~/.animation-studio/config.json, same rules as studio-core config.get).
                 new_scene.py stores this plugin's folder there (via studio-core check_tools.py --set) when it is
                 missing or points elsewhere. If the plugin cannot be found the shim stops and says how to refresh.
  make_scene.py  from a template (not overwritten unless --force):
                   example  "Pip and the Flower" - code-drawn character with full squash/stretch rig (6 s)
                   figure   an SVG figure from the characters skill (Fips/Tim/Lia or your own) with wrap= rig
                   blank    background + Pip from characters/pip_figure.py, beat list to fill in
                   none     only the shim (for comic / multiplane folders whose scripts import toon-2d modules)
Then: uv run make_scene.py ; render.py <scene>.sif
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parents[2]                               # <plugin>/skills/toon-2d/scripts -> <plugin>
ASSETS = SCRIPTS.parent / "assets"
TEMPLATES = {"example": ASSETS / "example_scene.py", "figure": ASSETS / "templates" / "figure_scene.py",
             "blank": ASSETS / "templates" / "blank_scene.py"}
KEY = "animation_studio_root"                           # machine config entry (env ANIMATION_STUDIO_ROOT)

SHIM = '''"""Path shim generated by toon-2d/scripts/new_scene.py: finds the animation-studio plugin at run time.

Lookup: env CLAUDE_PLUGIN_ROOT, then env ANIMATION_STUDIO_ROOT, then "animation_studio_root" in
~/.animation-studio/config.json (or the file named by ANIMATION_STUDIO_CONFIG). No path is stored here.
"""
import json
import os
import sys
from pathlib import Path


def _candidates():
    yield "env CLAUDE_PLUGIN_ROOT", os.environ.get("CLAUDE_PLUGIN_ROOT")
    yield "env ANIMATION_STUDIO_ROOT", os.environ.get("ANIMATION_STUDIO_ROOT")
    cfg = Path(os.environ.get("ANIMATION_STUDIO_CONFIG", Path.home() / ".animation-studio" / "config.json"))
    try:
        v = json.loads(cfg.read_text(encoding="utf-8")).get("animation_studio_root")
    except (OSError, ValueError):
        v = None
    yield f"animation_studio_root in {cfg}", v


def _find():
    tried = []
    for where, root in _candidates():
        if not root:
            continue
        scripts = Path(root) / "skills" / "toon-2d" / "scripts"
        if (scripts / "_studio.py").exists():
            return scripts
        tried.append(f"{where} = {root}")
    raise SystemExit(
        "animation-studio plugin not found for this scene folder ("
        + ("; ".join(tried) or "CLAUDE_PLUGIN_ROOT and animation_studio_root are not set") + ").\\n"
        "Refresh: python \\"<plugin>/skills/toon-2d/scripts/new_scene.py\\" \\"" + str(Path(__file__).resolve().parent)
        + "\\" --from none   (stores the current plugin folder; make_scene.py is kept)\\n"
        "or: python \\"<plugin>/skills/studio-core/scripts/check_tools.py\\" "
        "--set animation_studio_root=<plugin folder>")


_TOON = str(_find())
if _TOON in sys.path:
    sys.path.remove(_TOON)
sys.path.insert(0, _TOON)
import _studio  # noqa: E402
_studio.use("toon-2d", "characters")
'''


def remember_root():
    """Store this plugin's folder as the machine config entry the shims read (only if it differs)."""
    sys.path.insert(0, str(ROOT / "skills" / "studio-core" / "scripts"))
    import config
    cur = config.get(KEY)
    if cur and Path(cur).resolve() == ROOT:
        return
    subprocess.run([sys.executable, str(ROOT / "skills" / "studio-core" / "scripts" / "check_tools.py"), "--set",
                    f"{KEY}={ROOT}"], capture_output=True, text=True, errors="replace")
    if config.get(KEY) and Path(config.get(KEY)).resolve() == ROOT:
        print(f"machine config: {KEY} = {ROOT}" + (f" (was {cur})" if cur else ""))
    else:
        print(f"warning: could not store {KEY} in the machine config - set CLAUDE_PLUGIN_ROOT or run "
              f"check_tools.py --set {KEY}=<plugin folder> before running scene scripts")


def write_shim(folder):
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "_toon.py").write_text(SHIM, encoding="utf-8")
    remember_root()
    return folder / "_toon.py"


def main():
    ap = argparse.ArgumentParser(description="Create a toon-2d scene folder (path shim + make_scene.py template).")
    ap.add_argument("folder")
    ap.add_argument("--from", dest="template", default="blank", choices=sorted(TEMPLATES) + ["none"])
    ap.add_argument("--force", action="store_true", help="overwrite an existing make_scene.py")
    a = ap.parse_args()
    folder = Path(a.folder).resolve()
    print("shim:", write_shim(folder))
    dst = folder / "make_scene.py"
    if a.template == "none":
        return
    if dst.exists() and not a.force:
        print("kept existing", dst)
    else:
        shutil.copy(TEMPLATES[a.template], dst)
        print(f"template '{a.template}' ->", dst)
    print(f"next: cd \"{folder}\" && uv run make_scene.py")


if __name__ == "__main__":
    sys.exit(main())
